NO = object()
inf, nan = float("inf"), float("nan")

def norm_path(p):
    # oi: $.a[0] -> /a/0 ; others already JSON-pointer-ish
    if p.startswith("$"):
        return p[1:].replace("[", "/").replace("]", "").replace(".", "/")
    return p

def run(name, schema, inst):
    m = M[name]
    try:
        m.check_schema(schema); chk = "ok"
    except m.SchemaError: chk = "REJ"
    except Exception as e: chk = "CRASH:" + type(e).__name__
    if inst is NO: return chk, "-"
    try:
        r = m.validate(inst, schema)
        code = lambda e: getattr(e, "code", None) or getattr(e, "keyword", None)
        val = "valid" if not r else "inv:" + ",".join(f"{code(e)}@{norm_path(e.path)}" for e in r)
    except m.SchemaError: val = "SchemaError"
    except Exception as e: val = "CRASH:" + type(e).__name__
    return chk, val


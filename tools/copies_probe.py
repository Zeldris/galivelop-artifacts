_argv = sys.argv[1:]
for _i, _a in enumerate(_argv):
    if _a == "--copy":
        _name, _, _path = _argv[_i + 1].partition("=")
        if _name not in MODS or not _path:
            sys.exit("--copy NAME=PATH with NAME in " + ", ".join(MODS))
        ROOTS[_name] = _path
if len(ROOTS) < 2:
    sys.exit("give at least one --copy NAME=PATH (gdev, oi, gimg, gvoice)")
M = {}
for k, r in ROOTS.items():
    sys.path.insert(0, r)
